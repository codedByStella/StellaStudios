# engine/parts/youtube/node.py

import json
import os
import time
import shutil
from pathlib import Path
from typing import Optional

from engine.parts.core.logger import log_overview, log_detail, log_error
from engine.parts.youtube.uploader import upload_video_to_youtube


NODE_NAME = "YOUTUBE_UPLOADER"
FINALIZED_DIR = Path("REDACTED — production finalized-video directory")
ARCHIVE_DIR = Path("REDACTED — production video archive directory")
POLL_INTERVAL_SECONDS = 10


def ensure_directories():
    FINALIZED_DIR.mkdir(parents=True, exist_ok=True)
    ARCHIVE_DIR.mkdir(parents=True, exist_ok=True)


def _marker_path(video_path: Path) -> Path:
    return video_path.with_name(f".{video_path.name}.uploaded.json")


def find_next_video() -> Optional[Path]:
    """Return the next unsubmitted MP4, excluding files with upload markers."""
    videos = sorted(FINALIZED_DIR.glob("*.mp4"))
    for video in videos:
        if not _marker_path(video).exists():
            return video
    return None


def build_metadata_from_slug(slug: str) -> tuple[str, str, list[str]]:
    """Build the historical static metadata used by this independent uploader."""
    prettified = slug.replace("_", " ").replace("-", " ").title()
    title = f"ASMR {prettified}"
    description = (
        "Autogenerated ASMR video from Stella's engine.\n"
        "Soft whispers, gentle sounds, and cozy vibes.\n\n"
        "#asmr #relax #tingles"
    )
    tags = ["asmr", "relax", "sleep", "tingles", "whispers"]
    return title, description, tags


def move_to_archive(src: Path, video_id: Optional[str]) -> None:
    """Archive an uploaded file without overwriting an existing archive entry."""
    ARCHIVE_DIR.mkdir(parents=True, exist_ok=True)
    new_name = f"{src.stem}__yt_{video_id}{src.suffix}" if video_id else src.name
    dest = ARCHIVE_DIR / new_name
    if dest.exists():
        raise FileExistsError("YouTube archive destination already exists.")
    # Create the destination exclusively, stream the file, then remove the
    # source. This avoids rename() silently replacing a destination on POSIX.
    created = False
    try:
        with src.open("rb") as source_file, dest.open("xb") as dest_file:
            created = True
            shutil.copyfileobj(source_file, dest_file)
            dest_file.flush()
            os.fsync(dest_file.fileno())
        shutil.copystat(src, dest)
        src.unlink()
    except Exception:
        if created:
            try:
                dest.unlink(missing_ok=True)
            except OSError:
                pass
        raise
    log_detail("Video moved to archive.", component=NODE_NAME)


def _archive_marked_upload(video_path: Path, marker: Path) -> bool:
    """Resume archival for a provider-accepted upload after a prior move failure."""
    try:
        with marker.open("r", encoding="utf-8") as f:
            state = json.load(f)
        video_id = state.get("video_id") if isinstance(state, dict) else None
        if not isinstance(video_id, str) or not video_id:
            log_error(
                "YouTube upload outcome remains unresolved; automatic retry blocked pending manual review.",
                component=NODE_NAME,
            )
            return False
        move_to_archive(video_path, video_id)
        marker.unlink()
        return True
    except Exception as e:
        log_error(
            f"Unable to reconcile accepted YouTube upload: {type(e).__name__}",
            component=NODE_NAME,
        )
        return False


def _write_upload_marker(video_path: Path) -> Path:
    """Persist upload intent before contacting YouTube."""
    marker = _marker_path(video_path)
    payload = {"status": "upload_in_progress", "video_id": None}
    with marker.open("x", encoding="utf-8") as f:
        json.dump(payload, f)
        f.flush()
        os.fsync(f.fileno())
    return marker


def _mark_upload_accepted(marker: Path, video_id: str) -> None:
    """Record confirmed provider acceptance before local archival."""
    payload = {"status": "uploaded_archive_pending", "video_id": video_id}
    with marker.open("w", encoding="utf-8") as f:
        json.dump(payload, f)
        f.flush()
        os.fsync(f.fileno())


def process_video(video_path: Path) -> bool:
    marker = _marker_path(video_path)
    if marker.exists():
        return _archive_marked_upload(video_path, marker)

    # Persist intent before the network request. A crash or ambiguous response
    # must not cause the same file to be submitted again automatically.
    try:
        marker = _write_upload_marker(video_path)
    except FileExistsError:
        log_error("Upload marker already exists; duplicate submission prevented.", component=NODE_NAME)
        return False
    except Exception as e:
        log_error(
            f"Could not persist upload intent: {type(e).__name__}; request not sent.",
            component=NODE_NAME,
        )
        return False

    slug = video_path.stem
    title, description, tags = build_metadata_from_slug(slug)
    result = upload_video_to_youtube(
        file_path=video_path,
        title=title,
        description=description,
        tags=tags,
        privacy_status="unlisted",
    )

    if result.get("status") != "success":
        # Keep the intent marker: the provider outcome may be ambiguous.
        log_error(
            "YouTube upload failed or has an unconfirmed outcome; automatic retry blocked for manual review.",
            component=NODE_NAME,
        )
        return False

    video_id = result.get("video_id")
    if not isinstance(video_id, str) or not video_id:
        log_error(
            "Upload returned success without a video ID; automatic retry blocked for manual review.",
            component=NODE_NAME,
        )
        return False

    try:
        _mark_upload_accepted(marker, video_id)
    except Exception as e:
        # The original intent marker remains, preventing duplicate submission.
        log_error(
            f"Provider accepted upload but acceptance marker update failed: {type(e).__name__}; manual review required.",
            component=NODE_NAME,
        )
        return False

    return _archive_marked_upload(video_path, marker)


def run():
    ensure_directories()
    log_overview("YouTube uploader node starting up.", component=NODE_NAME)

    while True:
        try:
            # Recover accepted uploads before selecting new work.
            for marker in sorted(FINALIZED_DIR.glob(".*.mp4.uploaded.json")):
                original_name = marker.name[1:-len(".uploaded.json")]
                video_path = FINALIZED_DIR / original_name
                if video_path.is_file():
                    _archive_marked_upload(video_path, marker)

            video_path = find_next_video()
            if video_path:
                log_overview("Found video to upload.", component=NODE_NAME)
                process_video(video_path)
            else:
                time.sleep(POLL_INTERVAL_SECONDS)

        except KeyboardInterrupt:
            log_overview("YouTube uploader node received KeyboardInterrupt. Exiting.", component=NODE_NAME)
            break
        except Exception as e:
            log_error(f"Unexpected error in main loop: {type(e).__name__}", component=NODE_NAME)
            time.sleep(POLL_INTERVAL_SECONDS)
